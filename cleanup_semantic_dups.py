db = SessionLocal()
deleted_count = 0
updated_ads = 0

for m in merges:
    # delete bad regions
    deleted_count += db.query(models.Region).filter(models.Region.id.in_(m['bad_ids'])).delete(synchronize_session=False)
    
    # update ads
    for bad_name in m['bad_names']:
        ads = db.query(models.Ad).filter(
            (models.Ad.location.endswith(f', {bad_name}')) | 
            (models.Ad.location == bad_name)
        ).all()
        for ad in ads:
            if ad.location == bad_name:
                ad.location = m['keep_name']
            else:
                parts = ad.location.split(', ')
                parts[-1] = m['keep_name']
                ad.location = ', '.join(parts)
            updated_ads += 1

db.commit()
print(f'Deleted {deleted_count} bad region rows. Updated {updated_ads} Ad locations.')
