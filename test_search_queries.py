from search_parser import QueryParserService
import json

def test_queries():
    queries = [
        "شقة للبيع في تلاع العلي 150 متر بسعر لا يتجاوز 60 ألف",
        "فيلات مستقلة للبيع في دابوق إطلالة خلابة ومسبح",
        "رووف للبيع في ضاحية الرشيد مع تراس واسع",
        "شقق للبيع بالتقسيط من المالك مباشرة في الزرقاء الجديدة",
        "شقة أرضية للبيع في مرج الحمام مع حديقة ومدخل مستقل",
        "دوبلكس للبيع في عبدون تشطيبات سوبر ديلوكس",
        "بيت قديم للبيع في جبل اللويبدة يصلح للاستثمار السياحي",
        "شقة للبيع لقطة بداعي السفر في منطقة الجامعة الأردنية",
        "شقق تحت الإنشاء للبيع في خلدا بأسعار منافسة",
        "شقة نظام استوديو للبيع في إربد قرب جامعة اليرموك"
    ]

    for q in queries:
        parsed = QueryParserService.parse(q)
        print(f"======================")
        print(f"Query: {q}")
        print(f"Parsed Details: {json.dumps(parsed.model_dump(), ensure_ascii=False, indent=2)}")

if __name__ == "__main__":
    test_queries()
